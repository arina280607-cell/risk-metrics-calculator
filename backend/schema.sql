-- Схема PostgreSQL по bd.mmd.

BEGIN;

-- Справочник выпусков облигаций.
CREATE TABLE instruments (
    isin VARCHAR(12) PRIMARY KEY,
    name TEXT NOT NULL
);

-- Один набор данных за торговый день.
CREATE TABLE snapshot_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    as_of_date DATE NOT NULL UNIQUE,
    status TEXT NOT NULL CHECK (status IN ('LOADING', 'PUBLISHED')),
    published_at TIMESTAMPTZ
);

-- Курсы к рублю за ту же дату. Для RUB записывается курс 1.
CREATE TABLE fx_rates (
    snapshot_id BIGINT NOT NULL REFERENCES snapshot_batches(id),
    currency VARCHAR(3) NOT NULL,
    rub_per_unit NUMERIC NOT NULL CHECK (rub_per_unit > 0),

    PRIMARY KEY (snapshot_id, currency)
);

-- Параметры облигации в конкретном наборе данных.
CREATE TABLE instrument_parameters (
    snapshot_id BIGINT NOT NULL REFERENCES snapshot_batches(id),
    isin VARCHAR(12) NOT NULL REFERENCES instruments(isin),
    currency VARCHAR(3) NOT NULL,
    nominal NUMERIC NOT NULL CHECK (nominal > 0),
    dirty_quote_percent NUMERIC NOT NULL CHECK (dirty_quote_percent >= 0),
    modified_duration NUMERIC,
    convexity NUMERIC,
    coupon_type TEXT NOT NULL CHECK (coupon_type IN ('fixed', 'floating')),
    coupon_payments_per_year INTEGER CHECK (coupon_payments_per_year > 0),

    PRIMARY KEY (snapshot_id, isin),

    -- Курс берётся из того же набора данных, что и параметры облигации.
    FOREIGN KEY (snapshot_id, currency)
        REFERENCES fx_rates(snapshot_id, currency)
);

COMMIT;
